// 把 assets/ 下的 ESM 渲染/动效模块拼进 assets/widget.js。
//
// 为什么是拼接而不是动态 import：桌面端的 tapIndex 在宿主启动时一次性收集注入表，
// 新加独立 js 文件不会被注入（plan.md §1、§9.2）。因此模块源码仍以 ESM 形式维护
// （node 自测直接 import），发布时转成普通脚本内联进挂件。
//
// 每个模块包成独立 IIFE、依赖以变量显式注入，避免顶层重名
// （quat 与 skin-render 都有 identity/multiply，pet-state 与 gestures 都有 smooth，
//  挂件自身还有 scale/rotate/clamp/D/RIGHT/SNAP 等声明）。
//
// 用法：
//   node tools/build-widget.mjs          写入 assets/widget.js
//   node tools/build-widget.mjs --check  只校验产物能否生成，不写盘

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const ASSETS = path.join(ROOT, 'assets')
const WIDGET = path.join(ASSETS, 'widget.js')

const BEGIN = '// ==== DSH-PET BUNDLE BEGIN (generated by tools/build-widget.mjs) ===='
const END = '// ==== DSH-PET BUNDLE END ===='

// 顺序即依赖顺序：后出现的模块可以引用先出现的。
const MODULES = [
  { file: 'quat.js', varName: 'QUAT' },
  { file: 'skin-render.js', varName: 'SKIN_RENDER' },
  { file: 'skin-model.js', varName: 'SKIN_MODEL' },
  { file: 'gestures.js', varName: 'GESTURES' },
  { file: 'pet-state.js', varName: 'PET_STATE' },
  { file: 'pet-anim.js', varName: 'PET_ANIM' },
  { file: 'effects.js', varName: 'EFFECTS' },
  { file: 'decorations.js', varName: 'DECORATIONS' },
  { file: 'status-effects.js', varName: 'STATUS_EFFECTS' },
]

const moduleVar = new Map(MODULES.map((m) => [m.file.replace(/\.js$/, ''), m.varName]))

function exportedNames(body) {
  const names = []
  const re = /^export\s+(?:function|class|const|let|var)\s+([A-Za-z_$][\w$]*)/gm
  let m
  while ((m = re.exec(body))) names.push(m[1])
  const listRe = /^export\s*\{([^}]*)\}/gm
  while ((m = listRe.exec(body))) {
    for (const raw of m[1].split(',')) {
      const n = raw.trim().split(/\s+as\s+/).pop().trim()
      if (n) names.push(n)
    }
  }
  return [...new Set(names)]
}

// import {a, b} from './x.js'  →  var { a, b } = XVAR
// import * as Q from './quat.js' → var Q = QUAT
function transformBody(file, body) {
  const out = []
  for (const line of body.split(/\r?\n/)) {
    if (/^import\s+\*\s+as\s+\w+\s+from\s+['"]/.test(line)) {
      const m = line.match(/^import\s+\*\s+as\s+(\w+)\s+from\s+['"]\.\/([\w-]+)\.js['"]/)
      if (!m) throw new Error(`${file}: 无法解析的命名空间 import: ${line}`)
      const v = moduleVar.get(m[2])
      if (!v) throw new Error(`${file}: 未知依赖 ${m[2]}`)
      out.push(`var ${m[1]} = ${v}`)
      continue
    }
    const named = line.match(/^import\s+\{([^}]*)\}\s+from\s+['"]\.\/([\w-]+)\.js['"]/)
    if (named) {
      const v = moduleVar.get(named[2])
      if (!v) throw new Error(`${file}: 未知依赖 ${named[2]}`)
      out.push(`var {${named[1]}} = ${v}`)
      continue
    }
    if (/^import\s/.test(line)) throw new Error(`${file}: 无法解析的 import: ${line}`)
    if (/^export\s*\{/.test(line)) continue
    out.push(line.replace(/^export\s+/, ''))
  }
  return out.join('\n')
}

function buildBundle() {
  const parts = []
  parts.push('var DSH_PET = (function () {')
  for (const mod of MODULES) {
    const file = path.join(ASSETS, mod.file)
    const src = fs.readFileSync(file, 'utf8')
    const body = transformBody(mod.file, src)
    const names = exportedNames(src)
    if (!names.length) throw new Error(`${mod.file}: 没有收集到导出名`)
    parts.push(`var ${mod.varName} = (function () {`)
    parts.push(body)
    parts.push(`return { ${names.join(', ')} }`)
    parts.push('})()')
  }
  // note.png / heart.png 内嵌成 data URL：省一条路由、少一次请求，也避开"资源目录被清理"的情况。
  // 两张图合计 271 B，base64 后仍不足 400 字符。
  const dataUrl = (name) => 'data:image/png;base64,' + fs.readFileSync(path.join(ASSETS, name)).toString('base64')
  parts.push('return {')
  parts.push('  quat: QUAT,')
  parts.push('  render: SKIN_RENDER,')
  parts.push('  model: SKIN_MODEL,')
  parts.push('  gestures: GESTURES,')
  parts.push('  state: PET_STATE,')
  parts.push('  anim: PET_ANIM,')
  parts.push('  effects: EFFECTS,')
  parts.push('  decorations: DECORATIONS,')
  parts.push('  status: STATUS_EFFECTS,')
  parts.push(`  assets: { note: ${JSON.stringify(dataUrl('note.png'))}, heart: ${JSON.stringify(dataUrl('heart.png'))} },`)
  parts.push('}')
  parts.push('})()')
  return parts.join('\n')
}

function main() {
  const checkOnly = process.argv.includes('--check')
  const widget = fs.readFileSync(WIDGET, 'utf8')
  const bundle = buildBundle()

  const beginAt = widget.indexOf(BEGIN)
  const endAt = widget.indexOf(END)
  let next
  if (beginAt >= 0 && endAt > beginAt) {
    next = widget.slice(0, beginAt) + BEGIN + '\n' + bundle + '\n' + END + widget.slice(endAt + END.length)
  } else {
    const anchor = 'window.__dshWhaleWidget = true'
    const at = widget.indexOf(anchor)
    if (at < 0) throw new Error('挂件里找不到插入锚点 window.__dshWhaleWidget = true')
    const insertAt = at + anchor.length
    next = widget.slice(0, insertAt) + '\n\n' + BEGIN + '\n' + bundle + '\n' + END + widget.slice(insertAt)
  }

  const bytes = Buffer.byteLength(bundle, 'utf8')
  const lines = bundle.split('\n').length
  if (checkOnly) {
    console.log(`bundle ok: ${lines} 行 / ${bytes} 字节（未写盘）`)
    return
  }
  fs.writeFileSync(WIDGET, next, 'utf8')
  console.log(`bundle 写入 ${path.relative(ROOT, WIDGET)}: ${lines} 行 / ${bytes} 字节`)
}

main()
