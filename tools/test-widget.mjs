// R2 自检：assets/widget.js 是「构建产物 + 挂件壳」的合体文件，没法在 node 里直接跑 DOM，
// 所以分三层验：
//   ① 语法：整份文件能被解析（new Function）
//   ② 产物：把 BUNDLE 段抠出来在 node 里求值，逐个核对挂件壳用到的成员都在
//   ③ 接线：逐条 grep 挂件壳 —— 接口路径、localStorage 前缀、以及「不依赖 DWS」的反向断言
// 真机的观感（拖动/菜单/气泡）仍需人眼，见 prototype/pet-harness.html。

import fs from 'node:fs'
import { decodePng } from './png.mjs'

let pass = 0
let fail = 0
function check(name, ok, detail) {
  if (ok) {
    pass++
    console.log(`ok    ${name}`)
  } else {
    fail++
    console.log(`FAIL  ${name}${detail ? '  (' + detail + ')' : ''}`)
  }
}

const src = fs.readFileSync('assets/widget.js', 'utf8')

// ① 语法
let parsed = true
try {
  // eslint-disable-next-line no-new-func
  new Function(src)
} catch (err) {
  parsed = false
  console.log('      语法错误: ' + err.message)
}
check('widget.js 能作为普通脚本解析', parsed)

// ② 产物
const BEGIN = '// ==== DSH-PET BUNDLE BEGIN (generated by tools/build-widget.mjs) ===='
const END = '// ==== DSH-PET BUNDLE END ===='
const b = src.indexOf(BEGIN)
const e = src.indexOf(END)
check('含构建产物的起止标记', b >= 0 && e > b)
const bundleSrc = b >= 0 && e > b ? src.slice(b + BEGIN.length, e) : ''
check('BUNDLE 段非空', bundleSrc.trim().length > 10000, `${bundleSrc.length} B`)

let PET = null
try {
  PET = new Function(bundleSrc + '\nreturn DSH_PET')()
} catch (err) {
  console.log('      产物求值失败: ' + err.message)
}
check('产物能在 node 里求值', !!PET)
if (PET) {
  for (const k of ['quat', 'render', 'model', 'gestures', 'state', 'anim', 'effects', 'decorations', 'status', 'assets']) {
    check(`产物暴露 ${k}`, !!PET[k])
  }
  const renderFns = ['createFrame', 'clearFrame', 'skinFromImage', 'drawParts', 'toImageData', 'textureFromImage']
  check(
    'render 的六个函数都在',
    renderFns.every((f) => typeof PET.render[f] === 'function'),
    renderFns.filter((f) => typeof PET.render[f] !== 'function').join(',')
  )
  check('model.buildParts 在', typeof PET.model.buildParts === 'function')
  check('decorations.decorationParts 在', typeof PET.decorations.decorationParts === 'function')
  check('内置 note/heart 是 data URL', String(PET.assets.note).indexOf('data:image/png;base64,') === 0 && String(PET.assets.heart).indexOf('data:image/png;base64,') === 0)

  // 用产物真正渲染一帧：证明 bundle 不是"名字对但跑不起来"
  const skinImg = decodePng(fs.readFileSync('assets/default-skin.png'))
  const skin = PET.render.skinFromImage(skinImg)
  const frame = PET.render.createFrame(352, 416)
  PET.render.clearFrame(frame)
  PET.render.drawParts(frame, PET.model.buildParts(PET.model.defaultPose(), skin, { outer: true, armWidth: 4 }), skin)
  const rgba = PET.render.toImageData(frame)
  let opaque = 0
  for (let i = 3; i < rgba.length; i += 4) if (rgba[i] > 0) opaque++
  check('产物能渲染出一帧（非透明像素 > 20000）', opaque > 20000, `${opaque} px`)
  check('产物里的识别格检测可用（默认皮肤无眼睛）', skin.eyes === null)

  // 状态机 + 动效：挂件壳每帧都调这两个，接口签名必须对得上
  const m = new PET.state.PetStateMachine(0)
  const okForce = m.force('thinking', 0)
  const a = new PET.anim.PetAnimator(0)
  const pose = a.update(m.pose(10), { width: 352, height: 416, state: 'thinking', armWidth: 4 }, 0.2, 0.016)
  check('状态机 + 动效可组合运行', okForce && pose && typeof a.eyelid === 'number')
  check('动效暴露 counter / gestureBusy / gestureInput（挂件壳用到）', typeof a.counter === 'number' && 'gestureBusy' in a && typeof a.gestureInput === 'function')
}

// ③ 接线
const shell = src.slice(e >= 0 ? e : 0)
for (const p of ['/pet/state.json', '/pet/balance.json', '/pet/role.json', '/pet/skin.png', '/pet/audio-active.json']) {
  check(`挂件请求 ${p}`, src.indexOf(p) >= 0)
}
check('localStorage 统一用 dshmp- 前缀', (src.match(/'dshmp-/g) || []).length >= 5)
check('不残留 DWS 的 storage 前缀 dshw-', src.indexOf("'dshw") < 0)
check('不残留 DWS 的 CSS 类名 dshwv-', src.indexOf('dshwv-') < 0)
check('不引用旧挂件文件 whale-widget.js', src.indexOf('whale-widget.js') < 0)
check('不引用 DWS 立绘素材 DSniang', src.indexOf('DSniang') < 0)
check('挂载前先判 composer（data-composer-input）', shell.indexOf('[data-composer-input]') >= 0)
check('单像素 alpha 命中检测在位', shell.indexOf('frame.pixels[') >= 0 && shell.indexOf('> 8') >= 0)
check('帧需求分级：眨眼 / 跟随 / 拖动 → 60fps', shell.indexOf('eyelid < 0.999') >= 0 && shell.indexOf('cursorAt < 260') >= 0 && shell.indexOf('if (drag) return 2') >= 0)
check('idle 走 33ms（30fps）', shell.indexOf('IDLE_FRAME_MS = 33') >= 0)
check('穿透状态下留了恢复入口', shell.indexOf('dshmp-resume') >= 0)
check('有自检钩子 __dshPetState', shell.indexOf('window.__dshPetState') >= 0)

// ④ 未定义函数扫描：R2 第一版里 `startFrameLoop()` 这个不存在的函数把 init 整个炸掉，
//    画布全透明但所有断言都通过（因为没有任何断言真的执行过挂件）。这里静态兜住这一类错。
{
  const shellOnly = src.slice(e >= 0 ? e : 0)
  // 去掉注释，避免把注释里提到的名字算进来
  const code = shellOnly
    .replace(/\/\*[\s\S]*?\*\//g, ' ')
    .replace(/(^|[^:])\/\/.*$/gm, '$1')
    // 去掉字符串字面量：CSS 里的 translateY(7%) / scaleX(-1) 不是函数调用
    .replace(/'(?:[^'\\]|\\.)*'/g, "''")
    .replace(/"(?:[^"\\]|\\.)*"/g, '""')
  const defined = new Set()
  for (const m of code.matchAll(/function\s+([A-Za-z_$][\w$]*)\s*\(/g)) defined.add(m[1])
  for (const m of code.matchAll(/var\s+([A-Za-z_$][\w$]*)\s*=/g)) defined.add(m[1])
  const GLOBALS = new Set([
    'if', 'for', 'while', 'switch', 'catch', 'return', 'typeof', 'function', 'new', 'delete', 'in', 'of', 'void',
    'fetch', 'setTimeout', 'setInterval', 'clearInterval', 'clearTimeout', 'requestAnimationFrame', 'cancelAnimationFrame',
    'parseInt', 'parseFloat', 'isFinite', 'isNaN', 'String', 'Number', 'Boolean', 'Array', 'Object', 'Math', 'Date',
    'JSON', 'Map', 'Set', 'Promise', 'Image', 'ImageData', 'MutationObserver', 'KeyboardEvent', 'localStorage',
    'atob', 'btoa', 'encodeURIComponent', 'decodeURIComponent', 'console', 'Error', 'RegExp', 'Function',
  ])
  // 函数表达式的形参（resolve / reject 这类回调参数）也算已定义
  for (const m of code.matchAll(/function\s*\(([^)]*)\)/g)) {
    for (const raw of m[1].split(',')) {
      const n = raw.trim()
      if (n) defined.add(n)
    }
  }
  const missing = new Set()
  for (const m of code.matchAll(/(^|[^.\w$])([A-Za-z_$][\w$]*)\s*\(/g)) {
    const name = m[2]
    if (!defined.has(name) && !GLOBALS.has(name)) missing.add(name)
  }
  check('挂件壳里没有「调用了但没定义」的函数', missing.size === 0, [...missing].join(','))
  check('init 分步包了 try/catch（一步失败不会全灭）', code.indexOf('var steps = [injectCss') >= 0)
}

console.log(`\n${fail === 0 ? '全部通过' : fail + ' 项失败'}  (${pass} ok / ${fail} fail)`)
process.exit(fail === 0 ? 0 : 1)
